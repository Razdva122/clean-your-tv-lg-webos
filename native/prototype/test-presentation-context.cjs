const assert=require('node:assert/strict');
assert(require('node:fs').existsSync(require('node:path').join(__dirname,'../app/presentation-context.js')),'production presentation policy is missing');
const create=require('../app/presentation-context');
let now=10;
const p=create({now:()=>now,seed:100,content:id=>id==='test.video'});
assert.equal(p.context().content,null);
const first=p.begin('home');
assert.equal(p.observe(first,'test.video'),true);
assert.deepEqual(p.context(),{returnValue:true,eligible:true,content:true,generation:first,observedAgeMs:0});
assert.equal(p.begin('home',true),first,'repeated Home retains the owned activation');
now+=100;p.observe(first,'com.gathin.tvhome');
assert.equal(p.context().content,true,'activation of the host must preserve the still-fresh prelaunch observation');
assert.equal(p.context().observedAgeMs,100,'host foreground does not renew the underlay observation');
now+=2001;
assert.equal(p.context().eligible,false,'a cached foreground is not a fresh observation');
assert.equal(p.context().content,null,'stale is not proof of absence');
assert.equal(p.observe(first,'com.gathin.tvhome'),true);
assert.equal(p.context().content,null,'the host itself does not prove the underlay absent');
assert.equal(p.dismiss(first),true);
const next=p.begin('home');
assert.notEqual(next,first);
assert.equal(p.dismiss(first),false,'old dismissal cannot retire a new opening');
assert.equal(p.observe(first,'test.video'),false,'old SSAP reply cannot populate a new opening');
p.observe(next,'test.video');
p.invalidate();
assert.equal(p.context().eligible,false);
assert.equal(p.observe(next,'test.video'),false);
const boot=p.begin('startup');p.observe(boot,'test.video');
assert.equal(p.context().content,true);
assert.equal(p.context().eligible,false,'startup remains opaque even with active content');
for(const bad of [NaN,-1,1.5,Infinity,'100',9007199254740992])assert.equal(p.dismiss(bad),false);
console.log('PASS production presentation generations, fresh facts, opaque activation and stale dismissal fencing');
