#!/usr/bin/env python3
"""Fetch the TV's apps, icons and HDMI inputs into launcher/apps.js and launcher/icons/.

webOS does not let a third-party app list installed apps, so the launcher reads them from here.

    python3 sync-apps.py 192.168.1.50          # sync
    python3 sync-apps.py 192.168.1.50 --list   # just print app ids and titles

Needs: pip install websockets
"""
import asyncio
import json
import os
from pathlib import Path
import sys
from websockets.exceptions import ConnectionClosed

import lgtv
from cytv.tv import Inventory, include_tuner
from scripts.tv_web_build import launcher_inventory

APP_DIR = os.path.join(lgtv.HERE, "launcher")


async def required_list(ws, uri, field):
    payload = await lgtv.call(ws, uri, strict=True)
    items = payload.get(field)
    if not isinstance(items, list):
        raise ValueError("TV did not return a list for " + field)
    return items


def publish_inventory(app_dir, out, artwork):
    # Prepare the files beside the launcher so the build cannot see work in progress.
    destination = app_dir / "icons"
    with launcher_inventory(app_dir, write=True) as draft:
        if destination.is_symlink() or (destination.exists() and not destination.is_dir()):
            raise ValueError("Invalid launcher icon directory: " + str(destination))
        apps, icons = draft / "apps.js", draft / "icons"
        icons.mkdir()
        for name, data in artwork.items():
            (icons / name).write_bytes(data)
        apps.write_text("// Generated by sync-apps.py: the TV's apps and inputs.\n"
                        "window.TV_APPS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n",
                        encoding="utf-8")

        if destination.exists():
            destination.replace(draft / "previous-icons")
        icons.replace(destination)
        apps.replace(app_dir / "apps.js")


async def main(host, list_only):
    ws = await lgtv.session(host)
    try:
        points = await required_list(ws, "ssap://com.webos.applicationManager/listLaunchPoints", "launchPoints")
        if not list_only:
            inputs = await required_list(ws, "ssap://tv/getExternalInputList", "devices")
        try:
            installed = await lgtv.call(ws, "ssap://com.webos.applicationManager/listApps")
        except (OSError, TimeoutError, ConnectionClosed, json.JSONDecodeError, AttributeError):
            installed = None  # Optional transport/parser failure retains baseline.
        if isinstance(installed, dict) and installed.get("returnValue") is not False:
            points = include_tuner(points, installed.get("apps"))
    finally:
        await ws.close()

    if list_only:
        for p in points:
            print(f'{p["id"]:45} {p["title"]}')
        return

    app_dir = Path(APP_DIR)
    icons = Inventory(host.lower(), (app_dir / "brand-v2-icon.png").read_bytes())
    apps, artwork = [], {}
    for p in points:
        if p.get("hidden"):
            continue
        name = "".join(ch if ch.isalnum() or ch in "._-" else "_" for ch in p["id"]) + ".png"
        icon, _ = icons.icon_data(p)
        icon_path = ""
        if p["id"] != "com.webos.app.livetv" or icon != icons.fallback:
            artwork[name] = icon
            icon_path = "icons/" + name
        apps.append({
            "id": p["id"],
            "title": p["title"],
            "icon": icon_path,
            "iconColor": p.get("iconColor") or p.get("bgColor") or "",
        })
    if not apps:
        raise SystemExit("No apps were synced. Check TV pairing and make sure the TV has visible apps before retrying.")
    out = {
        "apps": apps,
        "inputs": [{"appId": d["appId"], "label": d.get("label") or d["id"]} for d in inputs if d.get("appId")],
    }
    publish_inventory(app_dir, out, artwork)
    print(f"Synced {len(apps)} apps and {len(out['inputs'])} inputs.")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    host = args[0] if args else os.environ.get("TV_HOST")
    if not host:
        sys.exit("usage: sync-apps.py <TV IP> [--list]")
    asyncio.run(main(host, "--list" in sys.argv))
